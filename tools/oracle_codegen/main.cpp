namespace {
std::string unit(std::size_t id) { return "unit" + std::to_string(id); }
std::string relative(const std::string& literal, const char* axis, std::size_t id) {
    const std::string base = std::string("GetUnit") + axis + "(" + unit(id) + ")";
    if (scenario::decimal_to_float(literal) == 0) return base;
    // Preserve the magnitude token; use subtraction just as MOV-0007 does.
    return base + (literal.front() == '-' ? " - " + literal.substr(1) : " + " + literal);
}
std::string generate(const scenario::Scenario& s, const std::string& hash,
                     const std::string& revision, const std::array<long double, 4>& bounds) {
    if (!(bounds[0] < bounds[1] && bounds[2] < bounds[3])) throw scenario::Error("invalid template bounds");
    // v1: the demonstrated 0.02 s generated sampler. v2 adds the other periods
    // already captured with oracle-v1 (JASS-0001, MOV-0012), a delayed start and
    // the MOV-0012 STATE event.
    const bool v2 = s.version == 2;
    if (!v2 && s.period_us != 20000) throw scenario::Error("generator v1 supports the demonstrated 0.02 s sampler only");
    if (v2 && s.period_us != 1000 && s.period_us != 10000 && s.period_us != 20000 && s.period_us != 25000
        && s.period_us != 50000)
        throw scenario::Error("generator v2 supports the captured 0.001/0.01/0.02/0.025/0.05 s samplers only");
    if (s.period_us * static_cast<std::uint64_t>(s.callbacks) >= 1000000000)
        throw scenario::Error("sampler must finish before the 1000 s library clock expires");
    const auto records = 4 + s.units.size() + (s.units.size() + 1) * (s.callbacks + 1) + s.actions.size()
        + (s.state_clock ? s.callbacks + 1 : 0);
    if (records > 50000) throw scenario::Error("schedule exceeds the trace contract's 50000 records");
    auto point = [&](const std::array<std::string, 2>& p) {
        for (std::size_t axis = 0; axis < 2; ++axis) {
            const auto value = std::stold(p[axis]);
            if (value < bounds[axis * 2] || value > bounds[axis * 2 + 1])
                throw scenario::Error("coordinate outside template playable bounds");
        }
    };
    for (const auto& u : s.units) {
        point(u.position_text);
        for (const auto& token : u.position_text) {
            const auto value = std::stold(token);
            if (std::floor(value) != value)
                throw scenario::Error("fractional CreateUnit placement is unobserved; v1 has no SetUnitX/Y");
        }
    }
    for (const auto& action : s.actions) {
        if (action.order == scenario::Order::stop) continue;
        if (!action.relative) point(action.point_text);
        else for (std::size_t axis = 0; axis < 2; ++axis)
            if (std::fabs(std::stold(action.point_text[axis])) > bounds[axis * 2 + 1] - bounds[axis * 2])
                throw scenario::Error("relative displacement exceeds template playable span");
    }
    // The caller's packaging revision must belong to this experiment. It does
    // not change or re-hash the scenario; both consumers still read those bytes.
    const auto suffix = revision.substr(std::min(revision.size(), s.experiment.size()));
    if (revision.size() > 64 || revision.compare(0, s.experiment.size(), s.experiment) != 0
        || (!suffix.empty() && (suffix.front() != '-' || suffix.back() == '-')) || suffix.find("--") != std::string::npos)
        throw scenario::Error("map revision must belong to this experiment");
    for (const char c : suffix)
        if (!(c == '-' || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')))
            throw scenario::Error("invalid map revision suffix");
    std::ostringstream out;
    out.imbue(std::locale::classic());
    out << "// Generated by oracle_codegen v" << s.version << "; do not edit.\n// scenario_sha256=" << hash
        << "\n// Packaging revision: " << revision << "; library: oracle-v1.\n\n";
    out << "function GeneratedHook takes nothing returns nothing\n";
    // Only relative hooks need local unit handles. Ordinary orders use exactly
    // the control's OracleUnit lookup at the point of the call.
    // The STATE event reads its unit and the setup's auxiliary clock, as MOV-0012 does.
    std::vector<bool> locals(s.units.size(), false);
    for (const auto& a : s.actions) locals[a.unit] = locals[a.unit] || a.relative;
    if (s.state_clock) locals[0] = true;
    for (std::size_t id = 0; id < s.units.size(); ++id)
        if (locals[id]) out << "    local unit " << unit(id) << " = OracleUnit(" << id << ")\n";
    if (s.state_clock) out << "    local timer clock = LoadTimerHandle(udg_OracleState, 3, 0)\n";
    std::uint64_t previous = 0;
    bool first = true;
    for (const auto& a : s.actions) {
        const auto callback = a.at_us / s.period_us;
        if (first || callback != previous) {
            out << (first ? "    if" : "    elseif") << " OracleCallback() == " << callback << " then\n";
            first = false;
            previous = callback;
        }
        const auto& name = s.units[a.unit].name;
        const auto handle = locals[a.unit] ? unit(a.unit) : "OracleUnit(" + std::to_string(a.unit) + ")";
        if (a.order == scenario::Order::stop)
            out << "        call OracleOrderImmediate(\"" << name << "\", " << handle << ", \"stop\")\n";
        else {
            const auto x = a.relative ? relative(a.point_text[0], "X", a.unit) : a.point_text[0];
            const auto y = a.relative ? relative(a.point_text[1], "Y", a.unit) : a.point_text[1];
            out << "        call OracleOrderPoint(\"" << name << "\", " << handle << ", \"move\", " << x << ", " << y << ")\n";
        }
    }
    if (!first) out << "    endif\n";
    // After this callback's actions, as in MOV-0012's hook.
    if (s.state_clock)
        out << "    call OracleEvent(\"STATE|c" << *s.state_clock << "_9=\" + R2SW(TimerGetElapsed(clock), 1, 9) + \"|x_9=\" + "
            << "R2SW(GetUnitX(unit0), 1, 9) + \"|y_9=\" + R2SW(GetUnitY(unit0), 1, 9) + \"|facing_9=\" + "
            << "R2SW(GetUnitFacing(unit0), 1, 9))\n";
    for (std::size_t id = 0; id < s.units.size(); ++id)
        if (locals[id]) out << "    set " << unit(id) << " = null\n";
    if (s.state_clock) out << "    set clock = null\n";
    out << "endfunction\n\n";
    const auto run = "    call OracleRun(" + s.period_text + ", " + std::to_string(s.callbacks) + ", function GeneratedHook)\n";
    // A delayed start uses the bootstrap's own mechanism: a single timer event trigger.
    if (s.start_us) out << "function GeneratedRun takes nothing returns nothing\n" << run << "endfunction\n\n";
    out << "function GeneratedStart takes nothing returns nothing\n";
    for (std::size_t id = 0; id < s.units.size(); ++id) out << "    local unit " << unit(id) << "\n";
    if (s.state_clock) out << "    local timer clock = CreateTimer()\n";
    if (s.start_us) out << "    local trigger starter = CreateTrigger()\n";
    out << "    call OracleBegin(\"" << s.experiment << "\", \"" << revision << "\", 1000)\n";
    // MOV-0002's independent control creates both units before configuring them.
    for (std::size_t id = 0; id < s.units.size(); ++id) {
        const auto& u = s.units[id];
        out << "    set " << unit(id) << " = CreateUnit(Player(0), '" << u.type << "', "
            << u.position_text[0] << ", " << u.position_text[1] << ", " << u.facing_text << ")\n";
    }
    for (std::size_t id = 0; id < s.units.size(); ++id) {
        const auto& u = s.units[id];
        out << "    call SetUnitAcquireRange(" << unit(id) << ", 0)\n";
        if (u.move_speed_text) out << "    call SetUnitMoveSpeed(" << unit(id) << ", " << *u.move_speed_text << ")\n";
    }
    out << "    call SetCameraPosition(384, 192)\n";
    for (std::size_t id = 0; id < s.units.size(); ++id)
        out << "    call OracleWatchUnit(\"" << s.units[id].name << "\", " << unit(id) << ")\n";
    // SETUP is declared input, not a prediction of speeds, placement or states.
    std::string setup = "scenario_sha256=" + hash + "|scenario_version=" + std::to_string(s.version);
    for (const auto& u : s.units) {
        setup += "|" + u.name + "=" + u.type + "," + u.position_text[0] + "," + u.position_text[1] + "," + u.facing_text;
        if (u.move_speed_text) setup += "|" + u.name + "_requested_move_speed=" + *u.move_speed_text;
    }
    for (std::size_t id = 0; id < s.actions.size(); ++id) {
        const auto& a = s.actions[id];
        setup += "|action" + std::to_string(id) + "=" + std::to_string(a.at_us / s.period_us) + "," + s.units[a.unit].name;
        setup += a.order == scenario::Order::stop ? ",stop" : ",move";
        if (a.order == scenario::Order::move)
            setup += (a.relative ? ",offset," : ",target,") + a.point_text[0] + "," + a.point_text[1];
    }
    if (v2) {
        setup += "|start=" + s.start_text;
        if (s.state_clock) setup += "|state_clock=" + std::to_string(*s.state_clock);
    }
    // Keep well below the JASS string/Preload line limit. Reject, never truncate.
    if (setup.size() > 900) throw scenario::Error("SETUP exceeds generator's 900-byte limit");
    out << "    call OracleSetup(\"" << setup << "\")\n";
    if (s.state_clock)
        out << "    call TimerStart(clock, " << *s.state_clock << ", false, null)\n"
            << "    call SaveTimerHandle(udg_OracleState, 3, 0, clock)\n";
    if (s.start_us)
        out << "    call TriggerRegisterTimerEventSingle(starter, " << s.start_text << ")\n"
            << "    call TriggerAddAction(starter, function GeneratedRun)\n";
    else
        out << run;
    for (std::size_t id = 0; id < s.units.size(); ++id) out << "    set " << unit(id) << " = null\n";
    if (s.state_clock) out << "    set clock = null\n";
    if (s.start_us) out << "    set starter = null\n";
    out << "endfunction\n\nfunction InitTrig_Melee_Initialization takes nothing returns nothing\n"
        << "    set gg_trg_Melee_Initialization = CreateTrigger()\n"
        << "    call TriggerRegisterTimerEventSingle(gg_trg_Melee_Initialization, 0.5)\n"
        << "    call TriggerAddAction(gg_trg_Melee_Initialization, function GeneratedStart)\nendfunction\n";
    return out.str();
}
}
int main(int argc, char** argv) {
    try {
#ifdef _WIN32
        if (_setmode(_fileno(stdout), _O_BINARY) == -1) throw scenario::Error("cannot select LF stdout");
#endif
        std::locale::global(std::locale::classic());
        if (argc != 7 && argc != 8)
            throw scenario::Error("usage: oracle_codegen SCENARIO MIN_X MAX_X MIN_Y MAX_Y TEMPLATE_SHA256 [MAP_REVISION]");
        std::ifstream file(argv[1], std::ios::binary);
        if (!file) throw scenario::Error("cannot read scenario");
        std::ostringstream text;
        text << file.rdbuf();
        const auto s = scenario::parse(text.str());
        std::array<long double, 4> bounds{};
        for (std::size_t i = 0; i < bounds.size(); ++i) {
            std::size_t used = 0;
            bounds[i] = std::stold(argv[i + 2], &used);
            if (used != std::string(argv[i + 2]).size() || !std::isfinite(bounds[i]))
                throw scenario::Error("invalid template bounds");
        }
        const std::string template_hash = argv[6];
        if (template_hash.size() != 64 || template_hash.find_first_not_of("0123456789abcdef") != std::string::npos)
            throw scenario::Error("invalid template digest");
        const auto result = generate(s, scenario::sha256_hex(text.str()), argc == 8 ? argv[7] : s.map_revision, bounds);
        // stdout is binary LF on Windows too.
        const auto complete = "// template_sha256=" + template_hash + "\n" + result;
        std::cout << complete;
        if (!std::cout) throw scenario::Error("cannot write JASS");
        return 0;
    } catch (const std::exception& error) {
        std::cerr << "oracle_codegen: " << error.what() << '\n';
        return 2;
    }
}
